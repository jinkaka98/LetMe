/**
 * Returns clean SVG markup string for a Lucide icon
 */
export function getLucideSvg(name: IconName, options: LucideIconOptions = {}): string {
  const size = options.size || 16;
  const strokeWidth = options.strokeWidth || 2;
  const color = options.color || 'currentColor';
  const className = options.className ? ` class="${options.className}"` : '';
  const style = options.style ? ` style="${options.style}"` : '';

  const innerPath = LUCIDE_PATHS[name] || LUCIDE_PATHS.info;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round"${className}${style}>${innerPath}</svg>`;
}

/**
 * Creates an SVGElement for a Lucide icon via standard DOM APIs
 */
export function createLucideIcon(name: IconName, options: LucideIconOptions = {}): SVGSVGElement {
  const size = options.size || 16;
  const strokeWidth = options.strokeWidth || 2;
  const color = options.color || 'currentColor';

  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', color);
  svg.setAttribute('stroke-width', String(strokeWidth));
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');

  if (options.className) {
    svg.setAttribute('class', options.className);
  }
  if (options.style) {
    svg.setAttribute('style', options.style);
  }

  svg.innerHTML = LUCIDE_PATHS[name] || LUCIDE_PATHS.info;
  return svg;
}
